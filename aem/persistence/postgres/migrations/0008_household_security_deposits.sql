-- Household security deposit slots and the sub-escrow between flatmates.
--
-- The landlord holds one lump-sum deposit for the lease. It belongs to the
-- household, not to whoever happens to live there, so it is divided into
-- permanent slots -- one per space in the flat -- that outlive the people who
-- occupy them. A slot is filled, funded, vacated and filled again; it is never
-- deleted. (A later phase attaches a room to each slot.)
--
-- None of this is operating money. A deposit is long-term capital held in
-- escrow, so nothing here reaches the monthly ledger, a statement, an expense,
-- or a resident's balance.
--
-- Two ways of funding the deposit, and the operator must say which -- there is
-- no default:
--   primary_signatory   one resident paid the landlord in full; the others
--                       reimburse that resident for their slot
--   direct_co_tenants   each flatmate pays the landlord, or a common escrow,
--                       directly
--
-- Money is BIGINT paise and never negative.

-- 1. The lease says how its deposit was funded, and by whom.
ALTER TABLE rent_lease_config
    ADD COLUMN deposit_funding_mode TEXT
        CHECK (deposit_funding_mode IS NULL
               OR deposit_funding_mode IN ('primary_signatory', 'direct_co_tenants')),
    ADD COLUMN deposit_primary_signatory_resident_id TEXT
        REFERENCES resident(resident_id) DEFERRABLE;

-- 2. The slots. Together their targets make up the deposit on the lease.
CREATE TABLE household_deposit_slot (
    slot_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    config_id TEXT REFERENCES rent_lease_config(config_id) DEFERRABLE,
    slot_number INTEGER NOT NULL CHECK (slot_number > 0),
    slot_label TEXT NOT NULL CHECK (length(trim(slot_label)) > 0),
    target_deposit_paise BIGINT NOT NULL CHECK (target_deposit_paise > 0),

    -- Who occupies the slot now. Null while it is vacant.
    assigned_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    assigned_since TEXT
        CHECK (assigned_since IS NULL OR assigned_since ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),

    status TEXT NOT NULL DEFAULT 'vacant'
        CHECK (status IN ('vacant', 'occupied_pending', 'occupied_funded', 'vacating')),

    -- What the current occupant has put in, and the latest payment towards it.
    funded_amount_paise BIGINT NOT NULL DEFAULT 0 CHECK (funded_amount_paise >= 0),
    funded_date TEXT
        CHECK (funded_date IS NULL OR funded_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    payment_method TEXT
        CHECK (payment_method IS NULL
               OR payment_method IN ('upi', 'bank_transfer', 'cash', 'direct_to_landlord')),
    payment_reference TEXT,
    paid_to_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,

    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    UNIQUE (apartment_id, slot_number),
    CHECK (funded_amount_paise <= target_deposit_paise),
    -- An empty slot holds nobody's money.
    CHECK (assigned_resident_id IS NOT NULL OR funded_amount_paise = 0),
    CHECK ((status = 'vacant') = (assigned_resident_id IS NULL))
);

-- A resident occupies at most one slot.
CREATE UNIQUE INDEX idx_deposit_slot_one_per_resident
    ON household_deposit_slot(assigned_resident_id) WHERE assigned_resident_id IS NOT NULL;

-- 3. What happened to each slot's money: payments in, and what was kept back
--    and handed over when somebody left. Rows are only ever added.
CREATE TABLE household_deposit_transaction (
    tx_id TEXT PRIMARY KEY,
    slot_id TEXT NOT NULL REFERENCES household_deposit_slot(slot_id) DEFERRABLE,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    resident_id TEXT NOT NULL REFERENCES resident(resident_id) DEFERRABLE,
    tx_type TEXT NOT NULL
        CHECK (tx_type IN ('funding_payment', 'move_out_deduction', 'move_out_refund',
                           'direct_replacement_transfer')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise >= 0),
    tx_date TEXT NOT NULL CHECK (tx_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    counterparty_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    payment_method TEXT,
    reference TEXT,
    notes TEXT,
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE INDEX idx_deposit_slot_apartment ON household_deposit_slot(apartment_id);
CREATE INDEX idx_deposit_tx_slot ON household_deposit_transaction(slot_id);
CREATE INDEX idx_deposit_tx_resident ON household_deposit_transaction(resident_id);
