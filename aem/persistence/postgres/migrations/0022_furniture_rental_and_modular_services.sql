-- 0022_furniture_rental_and_modular_services.sql: household services as
-- modules, starting with furniture rental (Furlenco, Rentomojo and the like).
--
-- A household service is one recurring arrangement the flat pays for. Each
-- type has its own module: furniture rental keeps the subscription and its
-- deposit, and the items rented. Each month's bill is generated from the items
-- into an ordinary expense, so the ledger never reads these tables.

CREATE TABLE household_service (
    service_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    service_type TEXT NOT NULL CHECK (service_type IN (
        'furniture_rental', 'broadband', 'domestic_help', 'water_tanker', 'cooking_gas')),
    display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
    provider_name TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'retired')),
    billing_day_of_month INTEGER CHECK (
        billing_day_of_month IS NULL OR (billing_day_of_month >= 1 AND billing_day_of_month <= 31)),
    period_rule TEXT NOT NULL DEFAULT 'current_month',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    retired_at TEXT,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CHECK ((status = 'retired') = (retired_at IS NOT NULL))
);

-- One live service of each type per flat; a retired one stays for the record.
CREATE UNIQUE INDEX ux_household_service_live_type
    ON household_service(apartment_id, service_type) WHERE status <> 'retired';

CREATE TABLE furniture_rental_config (
    service_id TEXT PRIMARY KEY REFERENCES household_service(service_id) ON DELETE CASCADE DEFERRABLE,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    provider_name TEXT NOT NULL DEFAULT 'furlenco',
    customer_id TEXT,
    subscription_reference TEXT,
    deposit_paid_paise BIGINT NOT NULL DEFAULT 0 CHECK (deposit_paid_paise >= 0),
    deposit_refunded_paise BIGINT NOT NULL DEFAULT 0 CHECK (deposit_refunded_paise >= 0),
    deposit_status TEXT NOT NULL DEFAULT 'held'
        CHECK (deposit_status IN ('held', 'partially_refunded', 'refunded')),
    -- The expense definition each month's bill is recorded under.
    expense_definition_id TEXT REFERENCES expense_definition(expense_definition_id) DEFERRABLE,
    notes TEXT,
    updated_at TEXT NOT NULL,
    CHECK (deposit_refunded_paise <= deposit_paid_paise)
);

CREATE TABLE furniture_rental_item (
    item_id TEXT PRIMARY KEY,
    service_id TEXT NOT NULL REFERENCES household_service(service_id) ON DELETE CASCADE DEFERRABLE,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    category TEXT NOT NULL CHECK (category IN (
        'living_room', 'bedroom', 'appliance', 'dining', 'workstation', 'other')),
    monthly_rent_paise BIGINT NOT NULL CHECK (monthly_rent_paise > 0),
    allocation_scope TEXT NOT NULL CHECK (allocation_scope IN ('common', 'resident')),
    assigned_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending_delivery', 'returned')),
    delivery_date TEXT,
    return_date TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- A common item is everyone's; a resident's item is exactly one person's.
    CHECK ((allocation_scope = 'common') = (assigned_resident_id IS NULL)),
    -- Returned items, and only they, carry the date they went back.
    CHECK ((status = 'returned') = (return_date IS NOT NULL)),
    CHECK (return_date IS NULL OR delivery_date IS NULL OR return_date >= delivery_date)
);

CREATE INDEX idx_furniture_rental_item_service ON furniture_rental_item(service_id);
CREATE INDEX idx_furniture_rental_item_resident ON furniture_rental_item(assigned_resident_id);
