-- The household's contacts and its document vault.
--
-- Contacts are the people the flat deals with: the owner, the broker, the
-- caretaker, the society manager, and emergency utility numbers. Each role has
-- a few fields of its own (an owner's PAN and bank details for HRA proof and
-- payouts, a broker's agency and fee), which are left null for other roles.
--
-- Documents are stored in the database itself, as BYTEA, so a backup of the
-- database is a backup of every agreement too. Each file's SHA-256 is taken on
-- the way in and kept beside it. Money is BIGINT paise.

CREATE TABLE household_contact (
    contact_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    role TEXT NOT NULL CHECK (
        role IN ('owner', 'broker', 'caretaker', 'society_manager', 'emergency_utility')),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    phone TEXT,
    email TEXT,

    -- The owner's details, for HRA proof and rent payouts.
    pan TEXT CHECK (pan IS NULL OR pan ~ '^[A-Z]{5}[0-9]{4}[A-Z]$'),
    bank_account_no TEXT,
    bank_ifsc TEXT CHECK (bank_ifsc IS NULL OR bank_ifsc ~ '^[A-Z]{4}0[A-Z0-9]{6}$'),
    upi_id TEXT,

    -- The broker's agency and fee.
    agency_name TEXT,
    fee_amount_paise BIGINT CHECK (fee_amount_paise IS NULL OR fee_amount_paise >= 0),
    fee_status TEXT CHECK (fee_status IS NULL OR fee_status IN ('paid', 'pending', 'na')),

    -- What a caretaker, society manager or utility line looks after.
    responsibilities TEXT,

    notes TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE INDEX idx_household_contact_apartment ON household_contact(apartment_id);
CREATE INDEX idx_household_contact_role ON household_contact(role);

CREATE TABLE household_document (
    doc_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    category TEXT NOT NULL CHECK (
        category IN ('lease_agreement', 'society_noc', 'police_verification',
                     'inventory_handover', 'other')),
    filename TEXT NOT NULL CHECK (length(trim(filename)) > 0),
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256 TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    content BYTEA NOT NULL,
    uploaded_by_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    notes TEXT,
    uploaded_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- The stored bytes are exactly as many as recorded.
    CHECK (octet_length(content) = size_bytes)
);

CREATE INDEX idx_household_document_apartment ON household_document(apartment_id);
CREATE INDEX idx_household_document_category ON household_document(category);
