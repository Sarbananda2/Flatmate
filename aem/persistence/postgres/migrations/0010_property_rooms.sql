-- The household's rooms.
--
-- The physical layer of the flat: each room, whether it has its own washroom
-- or a balcony, and who lives in it now. A room holds at most one resident,
-- and a resident occupies at most one room. Moving out frees the room.
--
-- A deposit slot may name the room it belongs to. The link is optional: slots
-- were set up before rooms existed, and a slot keeps its own label.

CREATE TABLE household_room (
    room_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    room_number TEXT NOT NULL CHECK (length(trim(room_number)) > 0),
    has_attached_washroom INTEGER NOT NULL DEFAULT 0 CHECK (has_attached_washroom IN (0, 1)),
    has_balcony INTEGER NOT NULL DEFAULT 0 CHECK (has_balcony IN (0, 1)),
    assigned_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    assigned_since TEXT
        CHECK (assigned_since IS NULL OR assigned_since ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    UNIQUE (apartment_id, room_number),
    -- NULLs are distinct, so any number of rooms can stand vacant.
    UNIQUE (apartment_id, assigned_resident_id),
    -- An occupied room says since when; a vacant one does not.
    CHECK ((assigned_resident_id IS NULL) = (assigned_since IS NULL))
);

CREATE INDEX idx_household_room_apartment ON household_room(apartment_id);
CREATE INDEX idx_household_room_resident ON household_room(assigned_resident_id);

ALTER TABLE household_deposit_slot
    ADD COLUMN room_id TEXT REFERENCES household_room(room_id) DEFERRABLE;
