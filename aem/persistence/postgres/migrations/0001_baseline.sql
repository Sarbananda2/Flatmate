-- The master lease. One active row per apartment. The contract-term columns
-- say when the current term starts and ends, how much notice the landlord
-- needs, what deposit is held, and how the rent escalates on renewal; nothing
-- there gates rent.
CREATE TABLE rent_lease_config (
    config_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    -- The expense definition rent is recorded under. It is what stops the
    -- recurring generator and the rent cycle from both creating a rent expense
    -- for the same month.
    expense_definition_id TEXT REFERENCES expense_definition(expense_definition_id) DEFERRABLE,
    landlord_name TEXT NOT NULL CHECK (length(trim(landlord_name)) > 0),
    landlord_phone TEXT,
    landlord_email TEXT,
    landlord_pan TEXT,
    landlord_bank_account TEXT,
    landlord_bank_ifsc TEXT,
    landlord_upi_id TEXT,
    monthly_rent_paise BIGINT NOT NULL CHECK (monthly_rent_paise > 0),
    due_day_of_month INTEGER NOT NULL DEFAULT 5 CHECK (due_day_of_month BETWEEN 1 AND 28),
    -- Most landlords confirm by bank reference only, so this is off by default.
    requires_landlord_receipt INTEGER NOT NULL DEFAULT 0
        CHECK (requires_landlord_receipt IN (0, 1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    lease_start_date TEXT,      -- YYYY-MM-DD
    lease_end_date TEXT,        -- YYYY-MM-DD, inclusive
    duration_months INTEGER DEFAULT 11 CHECK (duration_months > 0),
    notice_period_days INTEGER DEFAULT 30 CHECK (notice_period_days >= 0),
    lock_in_months INTEGER DEFAULT 6 CHECK (lock_in_months >= 0),
    security_deposit_paise BIGINT
        CHECK (security_deposit_paise IS NULL OR security_deposit_paise >= 0),
    escalation_type TEXT DEFAULT 'percent'
        CHECK (escalation_type IN ('percent', 'fixed', 'none')),
    escalation_percent DOUBLE PRECISION DEFAULT 5.0,
    -- The agreed rent for the next term, when escalation_type is 'fixed'.
    renewal_rent_paise BIGINT
        CHECK (renewal_rent_paise IS NULL OR renewal_rent_paise > 0),
    lease_status TEXT DEFAULT 'active'
        CHECK (lease_status IN ('active', 'notice_served', 'vacated', 'renewed')),
    notice_served_date TEXT,    -- YYYY-MM-DD
    target_handover_date TEXT,  -- YYYY-MM-DD
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

-- One rent cycle per apartment per settlement month.
--
-- total_rent_paise and participant_count record the cycle as generated and are
-- brought up to date when the landlord is paid, after which the row is frozen.
-- Who funded the payout is unknown until then, so disbursed_by stays NULL while
-- the cycle is pending rather than naming a funding source that has not been used.
CREATE TABLE rent_cycle (
    cycle_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    settlement_month TEXT NOT NULL
        CHECK (settlement_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    expense_id TEXT REFERENCES expense_instance(expense_id) DEFERRABLE,
    total_rent_paise BIGINT NOT NULL CHECK (total_rent_paise > 0),
    participant_count INTEGER NOT NULL CHECK (participant_count > 0),
    disbursement_status TEXT NOT NULL CHECK (disbursement_status IN ('pending', 'disbursed')),
    disbursed_at TEXT,              -- the date the landlord was paid, YYYY-MM-DD
    disbursement_reference TEXT,    -- UTR / UPI transaction ID
    disbursed_by TEXT CHECK (disbursed_by IN ('pool', 'resident_advance')),
    funding_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    funding_payment_id TEXT REFERENCES payment(payment_id) DEFERRABLE,
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    UNIQUE (apartment_id, settlement_month),
    CHECK (
        (disbursement_status = 'pending'
            AND disbursed_at IS NULL AND disbursed_by IS NULL
            AND disbursement_reference IS NULL
            AND funding_resident_id IS NULL AND funding_payment_id IS NULL)
        OR
        (disbursement_status = 'disbursed'
            AND disbursed_at IS NOT NULL AND disbursement_reference IS NOT NULL
            AND ((disbursed_by = 'pool'
                    AND funding_resident_id IS NULL AND funding_payment_id IS NULL)
              OR (disbursed_by = 'resident_advance'
                    AND funding_resident_id IS NOT NULL AND funding_payment_id IS NOT NULL)))
    )
);

-- HRA rent receipts, one per participant, written when the landlord is paid.
-- Each row carries everything the printed slip states, plus a SHA-256 over
-- those same fields. landlord_pan is '' when the lease has no PAN on file.
CREATE TABLE rent_receipt (
    receipt_id TEXT PRIMARY KEY,
    cycle_id TEXT NOT NULL REFERENCES rent_cycle(cycle_id) DEFERRABLE,
    resident_id TEXT NOT NULL REFERENCES resident(resident_id) DEFERRABLE,
    settlement_month TEXT NOT NULL,
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    landlord_name TEXT NOT NULL,
    landlord_pan TEXT NOT NULL,
    verification_hash TEXT NOT NULL CHECK (length(verification_hash) = 64),
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    UNIQUE (cycle_id, resident_id)
);

-- The landlord's own receipt, for leases where one is issued. Kept inside the
-- database so that a database backup is still a complete backup. It can be
-- replaced if the wrong file was chosen; each attachment and replacement is
-- recorded in the audit log with the file's SHA-256, which is why this table
-- is not append-only itself.
CREATE TABLE rent_landlord_receipt (
    cycle_id TEXT PRIMARY KEY REFERENCES rent_cycle(cycle_id) DEFERRABLE,
    filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256 TEXT NOT NULL CHECK (length(sha256) = 64),
    content BYTEA NOT NULL,
    uploaded_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

-- Completed lease terms, one row each, written when a lease is renewed. The
