BEFORE UPDATE ON audit_log FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: audit_log cannot be modified');

CREATE TRIGGER trg_audit_log_no_delete
BEFORE DELETE ON audit_log FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: audit_log cannot be deleted');

CREATE TRIGGER trg_statement_revision_no_update
BEFORE UPDATE ON statement_revision FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: statement revisions cannot be modified');

CREATE TRIGGER trg_statement_revision_no_delete
BEFORE DELETE ON statement_revision FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: statement revisions cannot be deleted');

CREATE TRIGGER trg_ledger_adjustment_no_update
BEFORE UPDATE ON ledger_adjustment FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: adjustments are corrected by a reversing adjustment');

CREATE TRIGGER trg_ledger_adjustment_no_delete
BEFORE DELETE ON ledger_adjustment FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: adjustments are corrected by a reversing adjustment');

-- Rent.
CREATE TRIGGER trg_rent_cycle_disbursed_no_update
BEFORE UPDATE ON rent_cycle FOR EACH ROW
WHEN (OLD.disbursement_status = 'disbursed')
EXECUTE FUNCTION aem_reject('append_only: a disbursed rent cycle cannot be changed');

CREATE TRIGGER trg_rent_cycle_disbursed_no_delete
BEFORE DELETE ON rent_cycle FOR EACH ROW
WHEN (OLD.disbursement_status = 'disbursed')
EXECUTE FUNCTION aem_reject('append_only: a disbursed rent cycle cannot be deleted');

