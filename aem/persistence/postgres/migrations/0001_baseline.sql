-- Baseline PostgreSQL schema.
--
-- This is the schema the application reached under SQLite (its migrations
-- 0001-0006), carried over table for table and column for column so that an
-- existing installation imports without any value being reinterpreted:
--
--   * IDs, dates, and timestamps are TEXT holding the same ISO-8601 strings.
--   * Flags are INTEGER 0/1. JSON documents are TEXT.
--   * Money is BIGINT paise. No floating-point column holds a financial value.
--   * The landlord's receipt file is BYTEA.
--
-- Two things are new, both because PostgreSQL has no equivalent built in:
--
--   * row_seq, on every table, is insertion order. SQLite's implicit rowid
--     played that role, and the order of charges, payments, and audit entries
--     recorded on the same date depends on it.
--   * Every foreign key is DEFERRABLE (but checked immediately by default), so
--     the one-off import from SQLite can load tables that refer to each other.
--
-- The database is expected to use the C collation, which sorts text by byte
-- value as SQLite did; scripts/local_postgres.sh creates it that way.

CREATE TABLE apartment (
    apartment_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    currency_code TEXT NOT NULL DEFAULT 'INR',
    timezone TEXT NOT NULL DEFAULT 'Asia/Kolkata',
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE resident (
    resident_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    display_name TEXT NOT NULL,
    active_from TEXT,
    active_until TEXT,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    email TEXT,
    phone TEXT,
    notes TEXT,
    created_at TEXT,
    updated_at TEXT,
    -- Optional, and never used for accounting: it only decorates what is shared.
    upi_id TEXT,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);

