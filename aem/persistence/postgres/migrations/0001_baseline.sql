-- --------------------------------------------------------------------------
-- Integrity guards.
--
-- These back up the service layer; they are the reason a closed statement
-- cannot be modified even by a direct SQL mistake. Each raises a message of
-- the form 'marker: explanation'. The application maps the marker to an API
-- error code, so the markers are part of the contract: closed_statement,
-- locked_statement, append_only, overapplied_payment, overapplied_charge,
-- invalid_application.
-- --------------------------------------------------------------------------

-- Raises its first argument. For guards whose whole condition fits in the
-- trigger's WHEN clause, or that have no condition at all.
CREATE FUNCTION aem_reject() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END;
$$;

CREATE FUNCTION aem_statement_status_of_expense(target_expense_id TEXT) RETURNS TEXT
LANGUAGE sql STABLE AS $$
    SELECT s.status
      FROM expense_instance e
      JOIN monthly_statement s ON s.statement_id = e.statement_id
     WHERE e.expense_id = target_expense_id;
$$;

-- Statements.
CREATE TRIGGER trg_statement_closed_is_immutable
BEFORE UPDATE ON monthly_statement FOR EACH ROW
WHEN (OLD.status = 'closed'
  AND (NEW.snapshot_json IS DISTINCT FROM OLD.snapshot_json
       OR NEW.status <> OLD.status
       OR NEW.settlement_month <> OLD.settlement_month
       OR NEW.apartment_id <> OLD.apartment_id
       OR NEW.finalized_at IS DISTINCT FROM OLD.finalized_at))
EXECUTE FUNCTION aem_reject('closed_statement: a closed statement snapshot is immutable');

CREATE TRIGGER trg_statement_closed_no_delete
BEFORE DELETE ON monthly_statement FOR EACH ROW
WHEN (OLD.status <> 'draft')
EXECUTE FUNCTION aem_reject('closed_statement: finalized statements cannot be deleted');

-- Expenses.
CREATE FUNCTION aem_expense_locked_no_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT status FROM monthly_statement
         WHERE statement_id = OLD.statement_id) = 'closed' THEN
        RAISE EXCEPTION 'closed_statement: expenses in a closed statement cannot be changed';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_expense_locked_no_update
BEFORE UPDATE ON expense_instance FOR EACH ROW
WHEN (OLD.statement_id IS NOT NULL)
EXECUTE FUNCTION aem_expense_locked_no_update();

CREATE FUNCTION aem_expense_locked_no_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT status FROM monthly_statement
         WHERE statement_id = OLD.statement_id) <> 'draft' THEN
        RAISE EXCEPTION 'locked_statement: expenses can only be removed from a draft statement';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_expense_locked_no_delete
BEFORE DELETE ON expense_instance FOR EACH ROW
WHEN (OLD.statement_id IS NOT NULL)
EXECUTE FUNCTION aem_expense_locked_no_delete();

-- Allocations.
CREATE FUNCTION aem_allocation_locked() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF aem_statement_status_of_expense(NEW.expense_id) = 'closed' THEN
            RAISE EXCEPTION 'closed_statement: allocations in a closed statement cannot be changed';
        END IF;
        RETURN NEW;
    END IF;
    IF aem_statement_status_of_expense(OLD.expense_id) = 'closed' THEN
        RAISE EXCEPTION 'closed_statement: allocations in a closed statement cannot be changed';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_allocation_locked_no_insert
BEFORE INSERT ON allocation FOR EACH ROW
EXECUTE FUNCTION aem_allocation_locked();

CREATE TRIGGER trg_allocation_locked_no_delete
BEFORE DELETE ON allocation FOR EACH ROW
EXECUTE FUNCTION aem_allocation_locked();

-- Payment applications.

-- An application settles exactly one thing: a charge or an opening debt.
CREATE TRIGGER trg_payment_application_single_target
BEFORE INSERT ON payment_application FOR EACH ROW
WHEN (NEW.allocation_id IS NOT NULL AND NEW.opening_balance_id IS NOT NULL)
EXECUTE FUNCTION aem_reject(
    'invalid_application: an application targets a charge or an opening balance, not both');

-- A payment can never be allocated beyond its own amount.
CREATE FUNCTION aem_application_within_payment() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT COALESCE(SUM(amount_paise), 0) FROM payment_application
         WHERE payment_id = NEW.payment_id)
       > (SELECT amount_paise FROM payment WHERE payment_id = NEW.payment_id) THEN
        RAISE EXCEPTION 'overapplied_payment: payment applications exceed the payment amount';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_payment_application_insert_within_payment
AFTER INSERT ON payment_application FOR EACH ROW
EXECUTE FUNCTION aem_application_within_payment();

CREATE TRIGGER trg_payment_application_update_within_payment
AFTER UPDATE ON payment_application FOR EACH ROW
EXECUTE FUNCTION aem_application_within_payment();

-- A charge can never be settled beyond its own amount.
CREATE FUNCTION aem_application_within_allocation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT COALESCE(SUM(amount_paise), 0) FROM payment_application
         WHERE allocation_id = NEW.allocation_id)
       > (SELECT amount_paise FROM allocation WHERE allocation_id = NEW.allocation_id) THEN
        RAISE EXCEPTION 'overapplied_charge: payment applications exceed the charge amount';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_payment_application_within_allocation
AFTER INSERT ON payment_application FOR EACH ROW
WHEN (NEW.allocation_id IS NOT NULL)
EXECUTE FUNCTION aem_application_within_allocation();

-- An opening debt can never be settled beyond its own amount, and an opening
-- credit (a positive amount) cannot be "settled" at all.
CREATE FUNCTION aem_application_within_opening_balance() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT COALESCE(SUM(amount_paise), 0) FROM payment_application
         WHERE opening_balance_id = NEW.opening_balance_id)
       > -(SELECT amount_paise FROM opening_balance
            WHERE opening_balance_id = NEW.opening_balance_id) THEN
        RAISE EXCEPTION 'overapplied_charge: payment applications exceed the opening balance owed';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_payment_application_within_opening_balance
AFTER INSERT ON payment_application FOR EACH ROW
WHEN (NEW.opening_balance_id IS NOT NULL)
EXECUTE FUNCTION aem_application_within_opening_balance();

CREATE TRIGGER trg_payment_application_update_within_opening_balance
AFTER UPDATE ON payment_application FOR EACH ROW
WHEN (NEW.opening_balance_id IS NOT NULL)
EXECUTE FUNCTION aem_application_within_opening_balance();

