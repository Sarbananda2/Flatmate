-- Paying a household service's provider, in parts if need be.
--
-- The same two steps as rent (0020): flatmates pay their shares into the
-- kitty when they can, and the provider -- Furlenco, Rentomojo, any service
-- module's -- is paid the month's bill out of the kitty, or by a resident from
-- their own account, in one payment or several. Each payment to the provider
-- is a tranche of its own, with its bank reference, recorded here.
--
-- A tranche is a fact about money that has left: it cannot be edited or
-- removed, and the tranches of a bill can never add up to more than the bill.

CREATE TABLE service_disbursement (
    disbursement_id TEXT PRIMARY KEY,
    service_id TEXT NOT NULL REFERENCES household_service(service_id) DEFERRABLE,
    expense_id TEXT NOT NULL REFERENCES expense_instance(expense_id) DEFERRABLE,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    settlement_month TEXT NOT NULL CHECK (settlement_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    disbursed_at TEXT NOT NULL,              -- the date the provider was paid, YYYY-MM-DD
    disbursement_reference TEXT NOT NULL CHECK (length(btrim(disbursement_reference)) > 0),
    disbursed_by TEXT NOT NULL CHECK (disbursed_by IN ('pool', 'resident_advance')),
    funding_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    funding_payment_id TEXT REFERENCES payment(payment_id) DEFERRABLE,
    note TEXT,
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CHECK ((disbursed_by = 'pool' AND funding_resident_id IS NULL AND funding_payment_id IS NULL)
        OR (disbursed_by = 'resident_advance'
            AND funding_resident_id IS NOT NULL AND funding_payment_id IS NOT NULL))
);

CREATE INDEX idx_service_disbursement_expense ON service_disbursement(expense_id);
CREATE INDEX idx_service_disbursement_apartment_month
    ON service_disbursement(apartment_id, settlement_month);

-- The tranches of a bill never add up to more than the bill.
CREATE FUNCTION aem_service_disbursement_within_bill() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT COALESCE(SUM(amount_paise), 0) FROM service_disbursement
         WHERE expense_id = NEW.expense_id)
       > (SELECT amount_paise FROM expense_instance WHERE expense_id = NEW.expense_id) THEN
        RAISE EXCEPTION 'overpaid_service: the payouts to the provider would exceed the bill';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_service_disbursement_within_bill
AFTER INSERT ON service_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_service_disbursement_within_bill();

CREATE TRIGGER trg_service_disbursement_no_update
BEFORE UPDATE ON service_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: a payout to a provider cannot be modified');

CREATE TRIGGER trg_service_disbursement_no_delete
BEFORE DELETE ON service_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: a payout to a provider cannot be deleted');

CREATE TRIGGER trg_service_disbursement_no_truncate
BEFORE TRUNCATE ON service_disbursement FOR EACH STATEMENT
EXECUTE FUNCTION aem_reject('append_only: payouts to providers cannot be deleted');

-- Each resident's payment to the furniture provider recorded so far becomes a
-- tranche of its own. A bill's expense names its definition, not its service:
-- a definition kept across a retired subscription and its successor belongs to
-- the latest of them. An advance recorded without a reference keeps none.
INSERT INTO service_disbursement (
    disbursement_id, service_id, expense_id, apartment_id, settlement_month, amount_paise,
    disbursed_at, disbursement_reference, disbursed_by, funding_resident_id,
    funding_payment_id, note, created_at)
SELECT disbursement_id, service_id, expense_id, apartment_id, settlement_month, amount_paise,
       disbursed_at, disbursement_reference, 'resident_advance', funding_resident_id,
       funding_payment_id, note, created_at
  FROM (SELECT DISTINCT ON (p.payment_id)
               'svcdisb_' || p.payment_id AS disbursement_id, s.service_id, e.expense_id,
               s.apartment_id,
               COALESCE(e.settlement_period, substr(e.expense_date, 1, 7)) AS settlement_month,
               p.amount_paise, p.payment_date AS disbursed_at,
               COALESCE(NULLIF(btrim(p.reference), ''), 'Not recorded')
                   AS disbursement_reference,
               p.payer_resident_id AS funding_resident_id, p.payment_id AS funding_payment_id,
               'Recorded before payouts were kept as tranches' AS note,
               COALESCE(p.created_at, p.payment_date) AS created_at, p.row_seq
          FROM payment p
          JOIN expense_instance e ON e.expense_id = p.expense_id
          JOIN furniture_rental_config c
            ON c.expense_definition_id = e.expense_definition_id
           AND c.apartment_id = e.apartment_id
          JOIN household_service s ON s.service_id = c.service_id
         WHERE p.payment_kind = 'provider_advance' AND p.status = 'active'
         ORDER BY p.payment_id, s.row_seq DESC) AS advance
 ORDER BY row_seq;
