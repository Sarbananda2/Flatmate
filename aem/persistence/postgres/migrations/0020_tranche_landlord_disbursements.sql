-- Paying the landlord in parts.
--
-- The landlord is due on a fixed day; flatmates pay the pool when they can. So
-- the household pays the landlord what it has collected by the due date and
-- the rest when it comes in. Each payment is a tranche of its own, with its
-- bank reference, recorded here; the month's rent cycle is 'pending' until the
-- first, 'partially_disbursed' while some is still owed to the landlord, and
-- 'disbursed' once all of it has been paid.
--
-- A tranche is a fact about money that has left: it cannot be edited or
-- removed, the tranches of a month can never add up to more than its rent,
-- and a month that has paid the landlord anything cannot be deleted.

-- The month's state now has a middle value.
ALTER TABLE rent_cycle DROP CONSTRAINT rent_cycle_disbursement_status_check;
ALTER TABLE rent_cycle ADD CONSTRAINT rent_cycle_disbursement_status_check
    CHECK (disbursement_status IN ('pending', 'partially_disbursed', 'disbursed'));

-- The cycle's own payout columns describe a single payout, which a month paid
-- in tranches no longer has: they now hold the latest tranche's date and
-- reference, and the funding columns stay as earlier single payouts left
-- them. The rule replacing the old one keeps what still holds.
ALTER TABLE rent_cycle DROP CONSTRAINT rent_cycle_check;
ALTER TABLE rent_cycle ADD CONSTRAINT rent_cycle_disbursement_state_check CHECK (
    (disbursement_status = 'pending'
        AND disbursed_at IS NULL AND disbursement_reference IS NULL
        AND disbursed_by IS NULL
        AND funding_resident_id IS NULL AND funding_payment_id IS NULL)
    OR
    (disbursement_status IN ('partially_disbursed', 'disbursed')
        AND disbursed_at IS NOT NULL AND disbursement_reference IS NOT NULL)
);

-- A month that has paid the landlord anything keeps its record.
DROP TRIGGER trg_rent_cycle_disbursed_no_delete ON rent_cycle;
CREATE TRIGGER trg_rent_cycle_disbursed_no_delete
BEFORE DELETE ON rent_cycle FOR EACH ROW
WHEN (OLD.disbursement_status <> 'pending')
EXECUTE FUNCTION aem_reject('append_only: a rent cycle with a landlord payout cannot be deleted');

CREATE TABLE rent_disbursement (
    disbursement_id TEXT PRIMARY KEY,
    cycle_id TEXT NOT NULL REFERENCES rent_cycle(cycle_id) DEFERRABLE,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    settlement_month TEXT NOT NULL CHECK (settlement_month ~ '^[0-9]{4}-[0-1][0-9]$'),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    disbursed_at TEXT NOT NULL,              -- the date the landlord was paid, YYYY-MM-DD
    disbursement_reference TEXT NOT NULL CHECK (length(btrim(disbursement_reference)) > 0),
    disbursed_by TEXT NOT NULL CHECK (disbursed_by IN ('pool', 'resident_advance')),
    funding_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    funding_payment_id TEXT REFERENCES payment(payment_id) DEFERRABLE,
    note TEXT,
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CHECK ((disbursed_by = 'pool' AND funding_resident_id IS NULL AND funding_payment_id IS NULL)
        OR (disbursed_by = 'resident_advance'
            AND funding_resident_id IS NOT NULL AND funding_payment_id IS NOT NULL))
);

CREATE INDEX idx_rent_disbursement_cycle ON rent_disbursement(cycle_id);
CREATE INDEX idx_rent_disbursement_apartment_month
    ON rent_disbursement(apartment_id, settlement_month);

-- The tranches of a month never add up to more than its rent.
CREATE FUNCTION aem_rent_disbursement_within_rent() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT COALESCE(SUM(amount_paise), 0) FROM rent_disbursement
         WHERE cycle_id = NEW.cycle_id)
       > (SELECT total_rent_paise FROM rent_cycle WHERE cycle_id = NEW.cycle_id) THEN
        RAISE EXCEPTION 'overpaid_rent: the landlord payouts would exceed the month''s rent';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_rent_disbursement_within_rent
AFTER INSERT ON rent_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_rent_disbursement_within_rent();

CREATE TRIGGER trg_rent_disbursement_no_update
BEFORE UPDATE ON rent_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: a landlord payout cannot be modified');

CREATE TRIGGER trg_rent_disbursement_no_delete
BEFORE DELETE ON rent_disbursement FOR EACH ROW
EXECUTE FUNCTION aem_reject('append_only: a landlord payout cannot be deleted');

CREATE TRIGGER trg_rent_disbursement_no_truncate
BEFORE TRUNCATE ON rent_disbursement FOR EACH STATEMENT
EXECUTE FUNCTION aem_reject('append_only: landlord payouts cannot be deleted');

-- Each month already paid in one payout becomes its single tranche.
INSERT INTO rent_disbursement (
    disbursement_id, cycle_id, apartment_id, settlement_month, amount_paise,
    disbursed_at, disbursement_reference, disbursed_by, funding_resident_id,
    funding_payment_id, note, created_at)
SELECT 'rentdisb_' || cycle_id, cycle_id, apartment_id, settlement_month, total_rent_paise,
       disbursed_at, disbursement_reference, COALESCE(disbursed_by, 'pool'),
       funding_resident_id, funding_payment_id, 'The month''s single payout', created_at
  FROM rent_cycle
 WHERE disbursement_status = 'disbursed'
 ORDER BY row_seq;
