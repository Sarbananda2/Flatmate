-- A resident's exit clearance.
--
-- When somebody moves out, four things are settled together: their move-out
-- date, their deposit slot, what they owe (or are owed) on the operating
-- ledger, and the cash that actually changes hands. This table keeps the one
-- record of that settlement, as it stood when it was made. Rows are only ever
-- added: a clearance is not edited afterwards.
--
-- Money is BIGINT paise. Every figure is a non-negative amount except
-- net_settlement_paise, whose sign says which way the cash goes.

CREATE TABLE resident_exit_clearance (
    clearance_id TEXT PRIMARY KEY,
    apartment_id TEXT NOT NULL REFERENCES apartment(apartment_id) DEFERRABLE,
    resident_id TEXT NOT NULL REFERENCES resident(resident_id) DEFERRABLE,
    move_out_date TEXT NOT NULL CHECK (move_out_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),

    -- The deposit slot they held, and what was put in and kept back.
    slot_id TEXT REFERENCES household_deposit_slot(slot_id) DEFERRABLE,
    deposit_funded_paise BIGINT NOT NULL DEFAULT 0 CHECK (deposit_funded_paise >= 0),
    deposit_deductions_paise BIGINT NOT NULL DEFAULT 0 CHECK (deposit_deductions_paise >= 0),
    deduction_reason TEXT,

    -- Their operating-ledger position at the time: what they owed the
    -- household, or what it owed them. At most one of the two is non-zero.
    ledger_outstanding_paise BIGINT NOT NULL DEFAULT 0 CHECK (ledger_outstanding_paise >= 0),
    ledger_credit_paise BIGINT NOT NULL DEFAULT 0 CHECK (ledger_credit_paise >= 0),
    -- Whether that position was netted into the settlement and cleared.
    net_ledger_offset_applied INTEGER NOT NULL DEFAULT 1
        CHECK (net_ledger_offset_applied IN (0, 1)),

    -- Positive: payable to the resident. Negative: payable by the resident.
    net_settlement_paise BIGINT NOT NULL,
    settlement_direction TEXT NOT NULL
        CHECK (settlement_direction IN ('refund_to_resident', 'payment_from_resident',
                                        'zero_balanced')),

    settlement_path TEXT NOT NULL
        CHECK (settlement_path IN ('signatory_refund', 'direct_replacement_transfer',
                                   'standalone_clearance')),
    settlement_date TEXT NOT NULL
        CHECK (settlement_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    settlement_reference TEXT,
    counterparty_resident_id TEXT REFERENCES resident(resident_id) DEFERRABLE,
    -- The ledger payment that cleared their operating balance, if there was one.
    clearing_payment_id TEXT REFERENCES payment(payment_id) DEFERRABLE,

    notes TEXT,
    created_at TEXT NOT NULL,
    row_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,

    CHECK (deposit_deductions_paise <= deposit_funded_paise),
    CHECK (ledger_outstanding_paise = 0 OR ledger_credit_paise = 0),
    CHECK ((settlement_direction = 'refund_to_resident' AND net_settlement_paise > 0)
        OR (settlement_direction = 'payment_from_resident' AND net_settlement_paise < 0)
        OR (settlement_direction = 'zero_balanced' AND net_settlement_paise = 0)),
    -- Without a deposit slot there is nothing to refund or deduct.
    CHECK ((settlement_path = 'standalone_clearance') = (slot_id IS NULL))
);

CREATE INDEX idx_clearance_apartment ON resident_exit_clearance(apartment_id);
CREATE INDEX idx_clearance_resident ON resident_exit_clearance(resident_id);
